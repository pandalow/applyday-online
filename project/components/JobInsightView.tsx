'use client'

import { useState } from 'react'
import { useLocale } from '@/locales'
import type { JobInsightContent, InsightVerdict, InsightRecommendation } from '@/app/db/schema'
import { card, cardHeader, cardBody, sectionLabel } from '@/app/lib/styles'

export const VERDICT_CONFIG: Record<InsightVerdict, { label: string; color: string; bg: string }> = {
  strong_fit:  { label: 'Strong Fit',  color: 'text-emerald-700 dark:text-emerald-400', bg: 'bg-emerald-50 dark:bg-emerald-900/20 border-emerald-200 dark:border-emerald-800' },
  good_fit:    { label: 'Good Fit',    color: 'text-blue-700 dark:text-blue-400',       bg: 'bg-blue-50 dark:bg-blue-900/20 border-blue-200 dark:border-blue-800' },
  stretch:     { label: 'Stretch',     color: 'text-amber-700 dark:text-amber-400',     bg: 'bg-amber-50 dark:bg-amber-900/20 border-amber-200 dark:border-amber-800' },
  low_fit:     { label: 'Low Fit',     color: 'text-red-700 dark:text-red-400',         bg: 'bg-red-50 dark:bg-red-900/20 border-red-200 dark:border-red-800' },
}

export const RECOMMENDATION_CONFIG: Record<InsightRecommendation, { label: string; icon: string }> = {
  strong_apply:         { label: 'Strong fit — apply now',                      icon: '🚀' },
  apply_with_tailoring: { label: 'Good fit — apply with resume updates',        icon: '✏️' },
  stretch:              { label: 'Stretch role — apply if genuinely interested', icon: '🎯' },
  low_fit:              { label: 'Low fit — consider your priorities',           icon: '⚠️' },
}

export function Section({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <div className={`${card} overflow-hidden`}>
      <div className={cardHeader}>
        <h3 className={sectionLabel}>{title}</h3>
      </div>
      <div className={cardBody}>{children}</div>
    </div>
  )
}

export function BulletList({ items, color = 'text-zinc-600 dark:text-zinc-300' }: { items: string[]; color?: string }) {
  if (!items?.length) return <p className="text-sm text-zinc-400">—</p>
  return (
    <ul className="space-y-1.5">
      {items.map((item, i) => (
        <li key={i} className={`flex gap-2 text-sm ${color}`}>
          <span className="text-zinc-300 dark:text-zinc-600 shrink-0 mt-0.5">•</span>
          <span>{item}</span>
        </li>
      ))}
    </ul>
  )
}

